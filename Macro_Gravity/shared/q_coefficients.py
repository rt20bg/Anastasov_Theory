def q_from_ep_fe(ep):
    """Fe I approximate q(EP) relation (Berengut 2004)."""
    return np.clip(1480.0 - 285.0 * np.asarray(ep), 50, 1800)

def get_lines_by_element(elem):
    """Return all lines for a given element."""
    return [row for row in Q_TABLE if row[0] == elem]

def get_all_elements():
    """Return sorted unique element list."""
    return sorted(set(row[0] for row in Q_TABLE))
